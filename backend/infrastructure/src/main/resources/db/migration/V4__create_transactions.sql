-- Movimientos de las cuentas. Una fila por movimiento: una transferencia son dos filas (débito en la
-- cuenta origen y crédito en la destino) unidas por la misma referencia. No se editan ni se borran.
CREATE TABLE transactions (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_id              BIGINT        NOT NULL,
    transaction_type        VARCHAR(10)   NOT NULL,
    direction               VARCHAR(6)    NOT NULL,
    amount                  NUMERIC(19,2) NOT NULL,
    balance_after           NUMERIC(19,2) NOT NULL,
    counterparty_account_id BIGINT,
    reference               UUID          NOT NULL,
    created_at              TIMESTAMP     NOT NULL,

    CONSTRAINT pk_transactions PRIMARY KEY (id),
    CONSTRAINT fk_transactions_account FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE RESTRICT,
    CONSTRAINT fk_transactions_counterparty FOREIGN KEY (counterparty_account_id) REFERENCES accounts (id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_transactions_type CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),
    CONSTRAINT ck_transactions_direction CHECK (direction IN ('CREDIT', 'DEBIT')),
    CONSTRAINT ck_transactions_amount_positive CHECK (amount > 0),
    -- La consignación siempre abona y el retiro siempre debita
    CONSTRAINT ck_transactions_deposit_is_credit CHECK (transaction_type <> 'DEPOSIT' OR direction = 'CREDIT'),
    CONSTRAINT ck_transactions_withdrawal_is_debit CHECK (transaction_type <> 'WITHDRAWAL' OR direction = 'DEBIT'),
    -- Solo la transferencia tiene contraparte, y nunca es la misma cuenta
    CONSTRAINT ck_transactions_counterparty CHECK (
        (transaction_type = 'TRANSFER') = (counterparty_account_id IS NOT NULL)
    ),
    CONSTRAINT ck_transactions_counterparty_not_self CHECK (counterparty_account_id <> account_id),
    -- Una operación tiene como máximo un débito y un crédito
    CONSTRAINT uq_transactions_reference_direction UNIQUE (reference, direction)
);

-- Estado de cuenta: movimientos de una cuenta del más reciente al más antiguo. El id desempata los
-- movimientos con la misma fecha. También sirve a la FK de account_id.
CREATE INDEX ix_transactions_account_created ON transactions (account_id, created_at DESC, id DESC);

CREATE INDEX ix_transactions_counterparty ON transactions (counterparty_account_id);
