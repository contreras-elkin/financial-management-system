-- Productos financieros (cuentas de ahorros y corrientes) de los clientes
CREATE TABLE accounts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_type VARCHAR(10)   NOT NULL,
    number       VARCHAR(10)   NOT NULL,
    status       VARCHAR(10)   NOT NULL,
    balance      NUMERIC(19,2) NOT NULL,
    gmf_exempt   BOOLEAN       NOT NULL,
    client_id    BIGINT        NOT NULL,
    created_at   TIMESTAMP     NOT NULL,
    updated_at   TIMESTAMP     NOT NULL,

    CONSTRAINT pk_accounts PRIMARY KEY (id),
    CONSTRAINT uq_accounts_number UNIQUE (number),
    -- Una cuenta solo existe vinculada a un cliente, y un cliente con cuentas no se puede eliminar
    CONSTRAINT fk_accounts_client FOREIGN KEY (client_id) REFERENCES clients (id) ON DELETE RESTRICT,
    CONSTRAINT ck_accounts_type CHECK (account_type IN ('SAVINGS', 'CHECKING')),
    CONSTRAINT ck_accounts_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'CANCELLED')),
    -- 10 dígitos: "53" para ahorros, "33" para corriente
    CONSTRAINT ck_accounts_number_format CHECK (
        (account_type = 'SAVINGS' AND number ~ '^53[0-9]{8}$')
        OR (account_type = 'CHECKING' AND number ~ '^33[0-9]{8}$')
    ),
    CONSTRAINT ck_accounts_savings_balance CHECK (account_type <> 'SAVINGS' OR balance >= 0),
    CONSTRAINT ck_accounts_cancelled_balance CHECK (status <> 'CANCELLED' OR balance = 0),
    CONSTRAINT ck_accounts_updated_after_created CHECK (updated_at >= created_at)
);

-- Este índice acelera las cuentas de un cliente
-- y la verificación del ON DELETE RESTRICT al eliminar un cliente.
CREATE INDEX ix_accounts_client_id ON accounts (client_id);

-- Una sola cuenta exenta de GMF no cancelada por cliente. El caso de uso lo verifica antes;
-- este índice único parcial lo garantiza ante peticiones concurrentes.
CREATE UNIQUE INDEX uq_accounts_client_gmf_exempt ON accounts (client_id)
    WHERE gmf_exempt AND status <> 'CANCELLED';

-- Generadores de los 8 dígitos que siguen al prefijo. Una secuencia por tipo, sin ciclo:
-- un número de cuenta nunca se reutiliza.
CREATE SEQUENCE savings_account_number_seq START WITH 1 MINVALUE 1 MAXVALUE 99999999 NO CYCLE;
CREATE SEQUENCE checking_account_number_seq START WITH 1 MINVALUE 1 MAXVALUE 99999999 NO CYCLE;
