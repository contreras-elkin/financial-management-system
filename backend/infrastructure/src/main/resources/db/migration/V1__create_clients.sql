-- Clientes de la entidad financiera
CREATE TABLE clients (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    identification_type   VARCHAR(2)   NOT NULL,
    identification_number VARCHAR(20)  NOT NULL,
    first_name            VARCHAR(100) NOT NULL,
    last_name             VARCHAR(100) NOT NULL,
    email                 VARCHAR(150) NOT NULL,
    birth_date            DATE         NOT NULL,
    created_at            TIMESTAMP    NOT NULL,
    updated_at            TIMESTAMP    NOT NULL,

    CONSTRAINT pk_clients PRIMARY KEY (id),
    CONSTRAINT uq_clients_identification UNIQUE (identification_type, identification_number),
    CONSTRAINT ck_clients_identification_type CHECK (identification_type IN ('CC', 'CE', 'PA')),
    CONSTRAINT ck_clients_first_name_length CHECK (char_length(trim(first_name)) >= 2),
    CONSTRAINT ck_clients_last_name_length CHECK (char_length(trim(last_name)) >= 2),
    CONSTRAINT ck_clients_email_format CHECK (email ~ '^[\w.+-]+@[\w-]+(\.[\w-]+)*\.[A-Za-z]{2,}$'),
    CONSTRAINT ck_clients_legal_age CHECK (birth_date <= (created_at - INTERVAL '18 years')::date),
    CONSTRAINT ck_clients_updated_after_created CHECK (updated_at >= created_at)
);
